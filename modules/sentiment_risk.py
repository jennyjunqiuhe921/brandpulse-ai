def _scan(text: str, words: list) -> list:
    return [w for w in words if w in text]


def classify(comments: str) -> dict:
    """对舆情样本做五级风险分级 + 行业标签 + 推荐回应场景。"""
    text = comments or ""

    level = 1
    hits_by_level = {}
    for lv in (5, 4, 3, 2):
        h = _scan(text, _RISK_KEYWORDS[lv])
        if h:
            hits_by_level[lv] = h
            level = max(level, lv)

    tags = {}
    for tag, words in _INDUSTRY_TAGS.items():
        h = _scan(text, words)
        if h:
            tags[tag] = h

    # 推荐回应场景（D2）
    scenarios = []
    if "食品安全" in tags or "卫生问题" in tags or level >= 5:
        scenarios.append("食安危机专项")
    if "服务态度" in tags or any(w in text for w in ["排队", "等太久", "服务", "态度"]):
        scenarios.append("服务投诉")
    if "产品质量" in tags:
        scenarios.append("产品质量")
    if "价格争议" in tags:
        scenarios.append("价格争议")
    # 始终给出好评互动话术（用于正向维护）
    scenarios.append("好评互动")
    # 去重保序
    seen, scen = set(), []
    for s in scenarios:
        if s not in seen:
            seen.add(s)
            scen.append(s)

    info = RISK_LEVELS[level]
    return {
        "level": level,
        "label": info["label"],
        "icon": info["icon"],
        "desc": info["desc"],
        "hits": hits_by_level,
        "tags": tags,
        "scenarios": scen,
    }


def templates_for(scenarios: list) -> list:
    """返回场景对应的话术模板列表 [(scenario, icon, [scripts])]。"""
    out = []
    for s in scenarios:
        t = RESPONSE_TEMPLATES.get(s)
        if t:
            out.append((s, t["icon"], t["scripts"]))
    return out
