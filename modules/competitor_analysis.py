def _get_preset(main_brand: str, competitor_brand: str) -> str | None:
    """Return preset demo text for this brand pair, or None if not available."""
    key = (main_brand, competitor_brand)
    if key in _DEMO:
        return _DEMO[key]
    # Try swapped order
    for k in _DEMO:
        if set(k) == {main_brand, competitor_brand}:
            return _DEMO[k]
    return None


def run(main_brand: str, competitor_brand: str) -> dict:
    # Use preset text only in DEMO_MODE AND a preset exists
    if is_demo_mode():
        preset = _get_preset(main_brand, competitor_brand)
        if preset:
            return {"output": preset, "chunks": [], "demo_mode": True}

    # For all other cases (real API, or no preset): call LLM with RAG context
    queries = [
        f"{BRAND_DISPLAY_NAMES[main_brand]} vs {BRAND_DISPLAY_NAMES[competitor_brand]} 品牌定位对比",
        f"{BRAND_DISPLAY_NAMES[competitor_brand]} 产品策略 内容营销 竞争优势",
    ]
    all_chunks = []
    seen = set()
    for brand_key in [main_brand, competitor_brand]:
        for q in queries:
            for chunk in retrieve(brand_key, q, n_results=3):
                if chunk["text"] not in seen:
                    seen.add(chunk["text"])
                    all_chunks.append(chunk)

    from core.llm_client import build_rag_context
    context = build_rag_context(all_chunks[:8])
    main_name = BRAND_DISPLAY_NAMES[main_brand]
    comp_name = BRAND_DISPLAY_NAMES[competitor_brand]

    system = (
        "你是专业的品牌竞争分析师。基于知识库内容进行克制、有依据的竞品对标分析。"
        "区分官方事实（✅）和AI推断（⚠️）。"
    )
    user_msg = f"""主品牌：{main_name}  竞品：{comp_name}

【知识库内容】
{context}

请输出完整竞品对标分析，包含：品牌定位对比表、产品卖点对比表、内容策略对比、AI/GEO可见度对比、对主品牌的策略建议。"""

    from core.llm_client import chat
    output = chat(system, user_msg, max_tokens=2500)
    return {"output": output, "chunks": all_chunks, "demo_mode": False}
