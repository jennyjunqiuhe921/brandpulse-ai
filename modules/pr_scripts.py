"""D5-2 · 双口径公关话术（对照 PRD Prompt4）。

四类场景：食品安全 / 团购退款 / 出餐慢 / 服务纠纷。
每条输出两套口径：
- 对外公开回复口径（公域平台，正式礼貌合规，食安引导私域）
- 内部市场处置口径（问题定性/处置底线/是否补偿/沟通策略/禁止话术）

纯模板（确定性、零 token、合规——不随意承诺）。接真实 AI 后可换 Prompt4。
"""
from __future__ import annotations

SCENARIOS = ["食品安全", "团购退款", "出餐慢", "服务纠纷"]

_EXTERNAL = {
    "食品安全": (
        "您好，非常感谢您的反馈，也对给您带来的不好体验深表歉意。食品安全是我们最重视的事，"
        "已第一时间记录您反映的情况。为更好地核实与处理，烦请您私信留下联系方式与门店信息，"
        "我们将尽快与您一对一沟通跟进。再次感谢您的监督。"),
    "团购退款": (
        "您好，给您带来不便十分抱歉。关于团购订单的退款问题，我们已收到您的反馈，"
        "可私信告知订单号，我们将协助核实并按平台规则尽快为您处理，感谢理解与支持。"),
    "出餐慢": (
        "您好，给您带来等待非常抱歉。高峰时段出餐确实可能较慢，我们正持续优化出餐流程。"
        "感谢您的反馈，欢迎再次光临，我们会努力做得更好。"),
    "服务纠纷": (
        "您好，对本次服务体验给您带来的困扰我们诚恳致歉。具体情况我们会认真核实，"
        "也欢迎您私信详细说明，我们将认真对待并妥善跟进。感谢您的反馈与监督。"),
}

_INTERNAL = {
    "食品安全": (
        "【问题定性】食品安全/卫生类，最高优先级，潜在监管与扩散风险。\n"
        "【处置底线】先止损：保留证据、第一时间私域承接，避免公域争辩；必要时停售自查。\n"
        "【是否补偿】视核实结果，按规定补偿/退款，留痕。\n"
        "【沟通策略】共情+核实+承诺跟进，引导至私域一对一。\n"
        "【禁止话术】禁止否认、甩锅、'绝对没问题'等绝对化承诺；禁止公开争论。"),
    "团购退款": (
        "【问题定性】交易/退款纠纷，中等风险。\n"
        "【处置底线】按平台规则与团购协议处理，不拖延。\n"
        "【是否补偿】符合规则的退款应尽快办理；超范围诉求需上报。\n"
        "【沟通策略】明确流程、给出时限、主动告知进度。\n"
        "【禁止话术】禁止推诿、含糊承诺、超权限答复。"),
    "出餐慢": (
        "【问题定性】效率/体验类，一般风险。\n"
        "【处置底线】致歉+说明高峰原因+改进措施。\n"
        "【是否补偿】可视情况给小额优惠券安抚，非强制。\n"
        "【沟通策略】共情+给预期+欢迎再来。\n"
        "【禁止话术】禁止辩解过度、归咎顾客。"),
    "服务纠纷": (
        "【问题定性】服务态度/沟通类，一般至中等风险。\n"
        "【处置底线】先安抚、核实当班记录、必要时门店复盘。\n"
        "【是否补偿】视核实结果合理安抚。\n"
        "【沟通策略】共情+核实+承诺改进，避免对错争论。\n"
        "【禁止话术】禁止与顾客争执、公开指责。"),
}


def generate(scenario: str, brand: str = "", detail: str = "") -> dict:
    """返回 {scenario, external, internal}。"""
    if scenario not in SCENARIOS:
        scenario = "服务纠纷"
    ext = _EXTERNAL[scenario]
    intl = _INTERNAL[scenario]
    if detail.strip():
        ext = ext + f"\n（针对具体反馈：{detail.strip()}）"
        intl = intl + f"\n【本次事件】{detail.strip()}"
    return {"scenario": scenario, "external": ext, "internal": intl}
