def _detect_brand(first_line: str) -> str:
    """Detect brand from a short, competitor-free string (first line of user msg or system head)."""
    if "奈雪" in first_line or "Nayuki" in first_line:
        return "nayuki"
    if "茶百道" in first_line or "ChaPanda" in first_line:
        return "chapanda"
    return "heytea"


def _demo_response(system: str, user: str) -> str:
    """Return a pre-written demo response based on context keywords and brand."""
    u = user + system
    # Use only the first line of user_msg (always "品牌：{brand_name}") +
    # first 100 chars of system (catches content_generator which embeds brand in system prompt).
    # Never pass the full message — RAG context contains competitor names.
    probe = user.split("\n")[0] + "\n" + system[:100]
    brand = _detect_brand(probe)

    if "GEO" in system or "可见度" in system:
        return _DEMO_GEO_MAP.get(brand, _DEMO_GEO_HEYTEA)
    if "合规" in system or ("风险" in system and "审查" in system):
        return _DEMO_COMPLIANCE
    if "舆情" in system:
        return _DEMO_SENTIMENT_MAP.get(brand, _DEMO_SENTIMENT_HEYTEA)
    if "内容创作" in system or "小红书" in u or "抖音" in u:
        return _DEMO_CONTENT_MAP.get(brand, _DEMO_CONTENT_HEYTEA)
    if "STP" in system or "SWOT" in system or "市场定位" in system:
        return _DEMO_POSITIONING_MAP.get(brand, _DEMO_POSITIONING_HEYTEA)
    if "产品分析" in system or "卖点" in system:
        return _DEMO_PRODUCT_MAP.get(brand, _DEMO_PRODUCT_HEYTEA)
    if "品牌战略" in system or "品牌分析" in system:
        return _DEMO_BRAND_MAP.get(brand, _DEMO_BRAND_HEYTEA)
    if "RefCheck" in system or "fact" in system.lower() or "核查" in system:
        return _DEMO_REFCHECK
    return _DEMO_BRAND_MAP.get(brand, _DEMO_BRAND_HEYTEA)


